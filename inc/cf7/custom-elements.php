/**
 * URL страницы политики конфиденциальности.
 *
 * @return string
 */
function tolstenko_cf7_privacy_url() {
	$page = get_page_by_path( 'privacy-policy' );
	if ( $page instanceof WP_Post ) {
		return (string) get_permalink( $page );
	}
	return home_url( '/privacy-policy/' );
}

/**
 * URL страницы согласия на обработку данных.
 *
 * @return string
 */
function tolstenko_cf7_agree_url() {
	foreach ( array( 'soglasie', 'personal-data', 'agreement', 'privacy-policy' ) as $slug ) {
		$page = get_page_by_path( $slug );
		if ( $page instanceof WP_Post ) {
			return (string) get_permalink( $page );
		}
	}
	return home_url( '/privacy-policy/' );
}

